"""Write installer/Instruments.iss: the installer's instrument families, downloaded from Hugging Face (D209).

Reads the packed zips (tools/release/package_library.py) for each family's exact unpacked size and the zip's
SHA-256, and writes one [Components] entry and one [Files] download-and-unpack entry per family. The file is
committed, so the release pipeline builds the installer without the library itself. Rerun it whenever the
library is packed again (a new library version).

usage: python make_installer_instruments.py <library-release-folder> <library-version> <dataset-id>
"""
import hashlib
import os
import sys
import zipfile

folder, version, dataset = sys.argv[1], sys.argv[2], sys.argv[3]
here = os.path.dirname(os.path.abspath(__file__))
out = os.path.normpath(os.path.join(here, "..", "..", "installer", "Instruments.iss"))

# In the order the installer lists them, with what is inside (resources/instruments/catalogue.txt).
FAMILIES = [
    ("keys", "Keys", "grand and upright pianos, two harpsichords, FM keys"),
    ("strings", "Strings", "violins, violas, cellos, double bass, solo violin"),
    ("plucked", "Plucked", "folk harp, dan tranh, kalimba"),
    ("brass", "Brass", "horn, trumpet, tuba, two trombones"),
    ("winds", "Winds", "flute, clarinet, bassoon, saxes, recorders, ocarina, harmonica, didgeridoo"),
    ("organs", "Organs", "pipe organ, renaissance organ"),
    ("mallets-and-bells", "Mallets and bells", "marimba, vibraphone, xylophone, bells, chimes, glasses, timpani"),
]

components, files, uninstall = [], [], []
for key, title, inside in FAMILIES:
    name = f"CoolSynth-Instruments-{key}-{version}.zip"
    path = os.path.join(folder, name)
    with zipfile.ZipFile(path) as z:
        unpacked = sum(i.file_size for i in z.infolist())
    digest = hashlib.sha256()
    with open(path, "rb") as h:
        for block in iter(lambda: h.read(1 << 20), b""):
            digest.update(block)
    component = "instruments\\" + key.replace("-", "")
    components.append(f'Name: "{component}"; Description: "{title}: {inside}"; Types: full')
    files.append(f'Source: "https://huggingface.co/datasets/{dataset}/resolve/main/{name}"; '
                 f'DestDir: "{{commonappdata}}\\CoolSynth"; DestName: "{name}"; ExternalSize: {unpacked}; '
                 f'Hash: "{digest.hexdigest()}"; Components: {component}; '
                 f'Flags: external download extractarchive ignoreversion recursesubdirs createallsubdirs')
    uninstall.append(f'Type: filesandordirs; Name: "{{commonappdata}}\\CoolSynth\\Library\\{key}"')
    print(f"{key}: {unpacked / 1e6:.0f} MB unpacked")

text = (f"; Generated by tools/release/make_installer_instruments.py from the instrument library {version}\n"
        f"; (https://huggingface.co/datasets/{dataset}). Do not edit by hand.\n\n"
        "[Components]\n"
        'Name: "instruments"; Description: "Recorded instruments (downloaded while installing)"; Types: full\n'
        + "\n".join(components) + "\n\n[Files]\n" + "\n".join(files) + "\n\n[UninstallDelete]\n"
        + "\n".join(uninstall) + '\nType: files; Name: "{commonappdata}\\CoolSynth\\Library\\library.index"\n')
with open(out, "w", encoding="utf-8", newline="\r\n") as h:
    h.write(text)
print("written", out)
